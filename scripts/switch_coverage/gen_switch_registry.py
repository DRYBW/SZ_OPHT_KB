#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_switch_registry.py -- write docs/SWITCH_COVERAGE_REGISTRY.tsv from the source, not by hand.

Every column is derived: the names come from `arm_hygiene.discover()` (a scan of mcp_server/ and
pipeline/ for `os.environ` reads), the harness column from the frozen recorded-set harness's own
SWITCHES tuple, and the answer-affecting column from the fail-closed classification in
`arm_hygiene.BENIGN`. Re-run it after adding a switch; `tests/gate_switch_coverage.py` fails when the
registry on disk no longer matches what the source says.
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import arm_hygiene as A  # noqa: E402

REPO = A.REPO
DEST = os.path.join(REPO, "docs", "SWITCH_COVERAGE_REGISTRY.tsv")

HEADER = [
    "# SWITCH_COVERAGE_REGISTRY -- every EYEKB_* environment name read by mcp_server/ or pipeline/,",
    "# with what happens to it between two measurement arms of the recorded set (28 volumes,",
    "# 721 clusters, 1,495,330 cells). Generated by scripts/switch_coverage/",
    "# gen_switch_registry.py -- regenerate rather than hand-edit, so the file cannot drift from",
    "# the source. Read it as: an arm that SETS a switch in the last column must set it in EVERY arm",
    "# of the same comparison, because the frozen harness will not clear it in between.",
    "name\tanswer_affecting\tcleared_by_recorded_harness\tmust_be_set_in_every_arm\tdisposition",
]


def rows():
    cleared = set(A.harness_switches())
    req = set(A.required_explicit())
    aa = set(A.answer_affecting())
    out = []
    for n in A.discover():
        if n not in aa:
            disp = "declared benign: %s" % A.BENIGN[n]
        elif n in cleared:
            disp = "cleared by the frozen harness before each arm; a before-arm setting cannot leak"
        else:
            disp = ("NOT cleared by the frozen harness -- any arm that sets it must set it in every "
                    "arm of the comparison, or the two arms collapse into a self-comparison")
        out.append("\t".join([n, "yes" if n in aa else "no", "yes" if n in cleared else "no",
                              "yes" if n in req else "no", disp]))
    return out


def main() -> int:
    text = "\n".join(HEADER + rows()) + "\n"
    with open(DEST, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d rows)" % (DEST, len(rows())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())